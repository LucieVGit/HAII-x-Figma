"""Gemini integration for the canonical Streamlit UXmethod app."""

from __future__ import annotations

import json
import os
import re

import streamlit as st


def get_api_key() -> str | None:
    for name in ("GEMINI_API_KEY", "GOOGLE_API_KEY"):
        value = os.getenv(name)
        if value and value.strip() and value.strip() != "your-api-key-here":
            return value.strip()
    try:
        return st.secrets.get("GEMINI_API_KEY") or st.secrets.get("GOOGLE_API_KEY")
    except Exception:
        return None


API_KEY = get_api_key()
MODEL = os.getenv("GEMINI_MODEL") or "gemini-3.8-flash"
BACKUP_MODELS = [
    model for model in ("gemini-3.7-flash", "gemini-3.5-flash", "gemini-3.5-flash-lite") if model != MODEL
]
st.session_state.setdefault("last_model", MODEL)


@st.cache_resource(show_spinner=False)
def _client(api_key: str):
    from google import genai
    from google.genai import types

    return genai.Client(api_key=api_key, http_options=types.HttpOptions(timeout=20_000))


def call_gemini(prompt: str, *, temperature: float, json_mode: bool = False) -> str:
    from google.genai import types

    config = types.GenerateContentConfig(
        temperature=temperature,
        response_mime_type="application/json" if json_mode else None,
    )
    candidates = list(dict.fromkeys([st.session_state.last_model, MODEL, *BACKUP_MODELS]))
    last_error: Exception | None = None
    for model in candidates:
        try:
            response = _client(API_KEY).models.generate_content(
                model=model,
                contents=prompt,
                config=config,
            )
            st.session_state.last_model = model
            return response.text or ""
        except Exception as error:  # noqa: BLE001
            if getattr(error, "code", None) in (400, 401, 403):
                raise
            last_error = error
    raise last_error or RuntimeError("Gemini request failed.")


def short_error(error: Exception) -> str:
    message = str(error).replace("\n", " ")
    return message[:220] + ("…" if len(message) > 220 else "")


def generate_brainstorm_prompts(project_context: str) -> tuple[list[str], str, str]:
    trimmed = project_context.strip()
    if not trimmed:
        return [], "ai", ""
    if not API_KEY:
        return [], "error", "Add a Gemini API key in Streamlit secrets to generate prompts."
    prompt = (
        "You are a UX ideation coach. Use every piece of the full project context below, including "
        "research notes and earlier decisions. Generate exactly 6 short, practical brainstorming "
        "prompts specific to this project. Return only the prompts, one per line, no numbering, "
        "no explanations, no markdown.\n\nFull project context:\n"
        f"{trimmed}"
    )
    try:
        content = call_gemini(prompt, temperature=0.9)
        prompts = [re.sub(r"^[-*•\d\s.]+", "", line).strip() for line in content.splitlines()]
        prompts = [prompt for prompt in prompts if len(prompt) > 12][:6]
        if prompts:
            return prompts, "ai", f"Generated by {st.session_state.last_model}"
        return [], "error", "Gemini returned no usable prompts."
    except Exception as error:  # noqa: BLE001
        return [], "error", f"Gemini error: {short_error(error)}"


def generate_coach_suggestions(phase: int, project_text: str, phases: list[dict], pages: list[dict]) -> list[dict]:
    page, info = pages[phase], phases[phase]
    prompt = f"""You are an AI coach helping beginner UX designers apply a book-based UX methodology.
Current phase: {info["title"]} ({info["subtitle"]}).
Methods available in this phase: {", ".join(info["steps"])}.
What the coach looks for at this stage: {page["why"]}

Read the designer's notebook below and return exactly 3 suggestions, ranked most important first,
as a JSON array. Each item must be an object with these keys:
- "type": "add" (something missing to add), "remove" (something to reframe, cut, or a bias to fix), or "consider" (an open question for the team to reflect on)
- "importance": "high", "medium" or "low"
- "label": 1-3 word badge
- "text": the suggestion, max 45 words, specific to the notebook content, citing the relevant method number
- "action": a 2-4 word button label
- "applyText": for "add"/"remove", one or two sentences the designer could append to their notebook; for "consider", an empty string
Write in the same language as the notebook. Do not invent research findings.

Notebook:
{project_text.strip()}"""
    raw = call_gemini(prompt, temperature=0.6, json_mode=True)
    data = json.loads(raw)
    if isinstance(data, dict):
        data = data.get("suggestions") or next((value for value in data.values() if isinstance(value, list)), [])
    if not isinstance(data, list):
        raise ValueError("Unexpected response format from Gemini.")

    suggestions = []
    for item in data[:3]:
        if not isinstance(item, dict) or not str(item.get("text", "")).strip():
            continue
        suggestion_type = item.get("type") if item.get("type") in ("add", "remove", "consider") else "consider"
        importance = item.get("importance") if item.get("importance") in ("high", "medium", "low") else "medium"
        suggestions.append(
            {
                "type": suggestion_type,
                "importance": importance,
                "label": str(item.get("label") or "Suggestion").strip()[:40],
                "text": str(item["text"]).strip(),
                "action": str(item.get("action") or ("Add comment" if suggestion_type == "consider" else "Apply")).strip()[:40],
                "applyText": "" if suggestion_type == "consider" else str(item.get("applyText") or "").strip(),
            }
        )
    if not suggestions:
        raise ValueError("Gemini returned no usable suggestions.")
    return suggestions


def analyze_ideas(ideas: list[str], context: str) -> list[dict]:
    fallback = [
        {
            "id": index + 1,
            "text": text,
            "dimension": "Needs review",
            "x": 18 + ((index * 29) % 70),
            "y": 22 + ((index * 41) % 60),
        }
        for index, text in enumerate(ideas)
    ]
    if not API_KEY or not ideas:
        return fallback
    prompt = (
        'Place each numbered idea on a useful creative dimension based on the full project context. '
        'Return only valid JSON with this shape: {"ideas":[{"id":1,"dimension":"short label","x":0,"y":0}]}. '
        "Use x and y values from 0 to 100 and include every idea exactly once.\n\n"
        f"Full project context:\n{context}\n\nIdeas:\n"
        + "\n".join(f"{index + 1}. {idea}" for index, idea in enumerate(ideas))
    )
    try:
        data = json.loads(call_gemini(prompt, temperature=0.3, json_mode=True))
        results = {
            int(item["id"]): item
            for item in data.get("ideas", [])
            if isinstance(item, dict) and str(item.get("id", "")).isdigit()
        }
        return [
            {
                **item,
                "id": index + 1,
                "text": text,
                "dimension": str(results.get(index + 1, {}).get("dimension") or "Needs review"),
                "x": max(0, min(100, int(results.get(index + 1, {}).get("x", item["x"])))),
                "y": max(0, min(100, int(results.get(index + 1, {}).get("y", item["y"])))),
            }
            for index, (text, item) in enumerate(zip(ideas, fallback))
        ]
    except Exception:
        return fallback
